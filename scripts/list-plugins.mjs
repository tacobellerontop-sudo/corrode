// Writes docs/BUILTIN_PLUGINS.md from the built-in plugin definitions.
// Usage: node scripts/list-plugins.mjs   (run it after adding or changing a built-in plugin)
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import * as esbuild from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tmp = mkdtempSync(join(tmpdir(), "corrode-plugins-"));
const out = join(tmp, "builtins.mjs");
await esbuild.build({ entryPoints: [join(root, "src/builtins/index.ts")], bundle: true, format: "esm", platform: "node", outfile: out, logLevel: "error" });
const { builtinPlugins } = await import(pathToFileURL(out).href);
rmSync(tmp, { recursive: true, force: true });

const cell = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
const groups = new Map();
for (const p of builtinPlugins) {
  const key = p.category ?? "Other";
  if (!groups.has(key)) groups.set(key, []);
  groups.get(key).push(p);
}
const names = [...groups.keys()].sort();
let md = `# Built-in plugins\n\nCorrode ships with ${builtinPlugins.length} plugins. All of them are off until you turn them on in\n**User Settings > Corrode > Plugins**, where you can search them or filter by group.\n\nThis file is generated by \`node scripts/list-plugins.mjs\`; don't edit it by hand.\n\n`;
md += names.map((n) => `- [${n}](#${n.toLowerCase().replace(/[^a-z0-9]+/g, "-")}) (${groups.get(n).length})`).join("\n") + "\n";
for (const n of names) {
  md += `\n## ${n}\n\n| Plugin | What it does |\n| --- | --- |\n`;
  for (const p of groups.get(n).sort((a, b) => a.name.localeCompare(b.name))) md += `| **${cell(p.name)}** | ${cell(p.description)} |\n`;
}
writeFileSync(join(root, "docs/BUILTIN_PLUGINS.md"), md);
console.log(`Wrote docs/BUILTIN_PLUGINS.md (${builtinPlugins.length} plugins in ${names.length} groups)`);
